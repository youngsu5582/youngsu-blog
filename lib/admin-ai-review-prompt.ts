export function buildAiReviewPrompt(data: Record<string, unknown>, content: string): string {
  return `당신은 이영수의 기술 블로그 발행 전 게이트를 맡은 에디터입니다. 다음 한국어 기술 블로그 포스트를 리뷰해주세요.

포스트 정보:
- 제목: ${data.title || ""}
- 설명: ${data.description || ""}
- 카테고리: ${Array.isArray(data.categories) ? data.categories.join(", ") : ""}
- tags: ${Array.isArray(data.tags) ? data.tags.join(", ") : ""}
- draft: ${String(data.draft ?? "")}

포스트 본문:
${content}

아래 항목들을 마크다운 형식으로 리뷰해주세요:

## ✅ 발행 전 체크리스트
- 제목/description/tags/categories가 독자에게 충분히 구체적인지
- 본문과 메타데이터가 서로 맞는지
- draft: false로 바꿔도 되는 수준인지, 아니면 보류해야 하는지

## 🗣️ 내 말투 점검
- 너무 AI스럽거나 과하게 정돈된 표현이 있는지
- 1인칭 회고/실전 기록 톤을 해치지 않는지
- 문장만 다듬되 글쓴이의 경험과 판단은 보존하는 방향의 수정 제안

## 🔐 민감정보 / 회사정보 / 홈서버 정보 노출
- 토큰, 키, 내부 경로, 사설 IP, 계정, 회사정보, 비공개 장애 맥락이 노출되는지
- 공개해도 되는 표현으로 바꾸는 구체적 제안

## 📝 글의 흐름
- 서론 → 본론 → 결론 구조가 자연스러운지
- 섹션 간 전환이 매끄러운지

## 🔍 문맥 및 논리
- 논리적 비약이 없는지
- 설명이 충분한지, 독자가 따라가기 쉬운지

## ✅ 좋은 점
- 잘 작성된 부분 구체적으로 언급

## ⚠️ 개선할 점
- 부족한 부분과 구체적인 개선 제안

## 📖 맞춤법 및 표현
- 맞춤법 오류나 어색한 표현 (있다면 수정 제안 포함)

## ⭐ 종합 평가
- 5점 만점 평가
- 한 줄 총평
- 최종 판단: 발행 가능 / 보완 후 발행 / 발행 보류 중 하나

솔직하고 건설적인 피드백을 한국어로 제공하세요. 마크다운 형식을 유지하세요.`;
}
